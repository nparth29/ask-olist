"""Run the gold SQL of every evaluation question locally, so Parth can verify each result by eye.

Local SQL only (read-only database, same guard as the app). No Gemini calls.
Parth sets `verified: true` in eval/questions.yaml himself; this script never changes the YAML.

Run:  python scripts/check_gold.py             (all; prints + writes reports/eval_gold_check.md)
      python scripts/check_gold.py q01 q02     (only these ids)
"""
import sqlite3
import sys
import time
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from ask_olist import db, guard  # noqa: E402

QUESTIONS = ROOT / "eval" / "questions.yaml"
EXAMPLES = ROOT / "examples" / "examples.yaml"
REPORT = ROOT / "reports" / "eval_gold_check.md"
EXPECTED_SPLIT = {"easy": 10, "medium": 12, "hard": 8}
PREVIEW_ROWS = 8


def normalise(text: str) -> str:
    return " ".join(text.lower().split())


def table(columns: list[str], rows: list[tuple]) -> str:
    lines = ["| " + " | ".join(columns) + " |", "|" + "|".join("---" for _ in columns) + "|"]
    lines += ["| " + " | ".join("NULL" if v is None else str(v) for v in r) + " |" for r in rows]
    return "\n".join(lines)


def main() -> int:
    questions = yaml.safe_load(QUESTIONS.read_text(encoding="utf-8"))
    examples = yaml.safe_load(EXAMPLES.read_text(encoding="utf-8"))
    wanted = set(sys.argv[1:])
    selected = [q for q in questions if not wanted or q["id"] in wanted]

    out, failures = [], 0
    for q in selected:
        out += [f"## {q['id']} ({q['difficulty']}): {q['question']}", "",
                f"verified: {q['verified']}   traps: {q['traps']}   order matters: {q['order_matters']}", "",
                "```sql", q["gold_sql"].strip(), "```", ""]
        started = time.perf_counter()
        try:
            result = db.run_query(guard.check_sql(q["gold_sql"]))
        except (guard.GuardError, sqlite3.Error) as exc:
            failures += 1
            out += [f"**ERROR:** {type(exc).__name__}: {exc}", ""]
            continue
        shown = result.rows[:PREVIEW_ROWS]
        out += [f"{len(result.rows)} row(s), {time.perf_counter() - started:.2f}s. First {len(shown)}:", "", table(result.columns, shown), ""]

    if not wanted:
        split = Counter(q["difficulty"] for q in questions)
        with_traps = sum(bool(q["traps"]) for q in questions)
        example_questions = {normalise(e["question"]) for e in examples}
        example_sql = {normalise(e["sql"]) for e in examples}
        same_question = [q["id"] for q in questions if normalise(q["question"]) in example_questions]
        same_sql = [q["id"] for q in questions if normalise(q["gold_sql"]) in example_sql]
        ids = [q["id"] for q in questions]
        out += [
            "## Checks", "",
            f"- questions: {len(questions)}, verified: {sum(q['verified'] is True for q in questions)}, gold SQL that failed to run: {failures}",
            f"- difficulty split: {dict(split)} (expected {EXPECTED_SPLIT}) -> {'OK' if dict(split) == EXPECTED_SPLIT else 'MISMATCH'}",
            f"- questions that test at least one data trap: {with_traps} (need 8 or more) -> {'OK' if with_traps >= 8 else 'TOO FEW'}",
            f"- trap numbers covered: {sorted({t for q in questions for t in q['traps']})}",
            f"- ids unique: {len(ids) == len(set(ids))}",
            f"- same question text as an example: {same_question or 'none'}",
            f"- same SQL as an example: {same_sql or 'none'}", "",
        ]

    text = "\n".join(out)
    print(text)
    if not wanted:
        REPORT.write_text("# Evaluation gold SQL check (generated by scripts/check_gold.py)\n\n" + text, encoding="utf-8")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
