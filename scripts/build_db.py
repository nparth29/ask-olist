"""Build data/olist.db from the 9 raw CSVs and write reports/db_summary.md.

Run once:  python scripts/build_db.py
After this, the app only ever opens the database read-only.
"""
import sqlite3
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from ask_olist.config import DB_PATH, RAW_DIR  # noqa: E402

REPORT = ROOT / "reports" / "db_summary.md"

# csv file -> table name
TABLES = {
    "olist_customers_dataset.csv": "customers",
    "olist_geolocation_dataset.csv": "geolocation",
    "olist_order_items_dataset.csv": "order_items",
    "olist_order_payments_dataset.csv": "order_payments",
    "olist_order_reviews_dataset.csv": "order_reviews",
    "olist_orders_dataset.csv": "orders",
    "olist_products_dataset.csv": "products",
    "olist_sellers_dataset.csv": "sellers",
    "product_category_name_translation.csv": "category_translation",
}

# Only non-TEXT columns are listed; everything else is TEXT.
# Zip prefixes stay TEXT on purpose: they have leading zeros ("09790").
INTEGER_COLS = {
    "order_items": ["order_item_id"],
    "order_payments": ["payment_sequential", "payment_installments"],
    "order_reviews": ["review_score"],
    "products": ["product_name_lenght", "product_description_lenght", "product_photos_qty"],
}
REAL_COLS = {
    "geolocation": ["geolocation_lat", "geolocation_lng"],
    "order_items": ["price", "freight_value"],
    "order_payments": ["payment_value"],
    "products": ["product_weight_g", "product_length_cm", "product_height_cm", "product_width_cm"],
}
# Stored as ISO text 'YYYY-MM-DD HH:MM:SS' (already that format in the CSVs).
TIMESTAMP_COLS = {
    "orders": [
        "order_purchase_timestamp", "order_approved_at", "order_delivered_carrier_date",
        "order_delivered_customer_date", "order_estimated_delivery_date",
    ],
    "order_items": ["shipping_limit_date"],
    "order_reviews": ["review_creation_date", "review_answer_timestamp"],
}
INDEXES = {
    "customers": ["customer_id", "customer_unique_id"],
    "order_items": ["order_id", "product_id", "seller_id"],
    "order_payments": ["order_id"],
    "order_reviews": ["order_id", "review_id"],
    "orders": ["order_id", "customer_id"],
    "products": ["product_id"],
    "sellers": ["seller_id"],
}


def column_type(table: str, col: str) -> str:
    if col in INTEGER_COLS.get(table, []):
        return "INTEGER"
    if col in REAL_COLS.get(table, []):
        return "REAL"
    return "TEXT"


def load_csv(path: Path, table: str) -> pd.DataFrame:
    # Read as text first so we control every type ourselves.
    df = pd.read_csv(path, dtype=str, keep_default_na=True)
    for col in INTEGER_COLS.get(table, []):
        df[col] = pd.to_numeric(df[col]).astype("Int64")
    for col in REAL_COLS.get(table, []):
        df[col] = pd.to_numeric(df[col]).astype("float64")
    for col in TIMESTAMP_COLS.get(table, []):
        # Parse then re-format, so a malformed value fails loudly instead of slipping in.
        df[col] = pd.to_datetime(df[col], format="%Y-%m-%d %H:%M:%S").dt.strftime("%Y-%m-%d %H:%M:%S")
    return df


def create_table(con: sqlite3.Connection, table: str, df: pd.DataFrame) -> None:
    cols = ", ".join(f'"{c}" {column_type(table, c)}' for c in df.columns)
    con.execute(f"CREATE TABLE {table} ({cols})")


def main() -> None:
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    DB_PATH.unlink(missing_ok=True)  # rebuild from scratch every time
    con = sqlite3.connect(DB_PATH)

    rows = []
    for csv_name, table in TABLES.items():
        df = load_csv(RAW_DIR / csv_name, table)
        create_table(con, table, df)
        df.to_sql(table, con, if_exists="append", index=False, chunksize=20000)
        for col in INDEXES.get(table, []):
            con.execute(f"CREATE INDEX idx_{table}_{col} ON {table}({col})")
        db_count = con.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
        rows.append((csv_name, table, len(df), db_count))
        print(f"{table}: csv={len(df)} db={db_count}")
    con.commit()
    con.close()

    write_report(rows)
    if any(csv_n != db_n for _, _, csv_n, db_n in rows):
        raise SystemExit("Row counts do not match!")


def write_report(rows: list[tuple[str, str, int, int]]) -> None:
    lines = [
        "# Database summary",
        "",
        "Generated by `scripts/build_db.py`. CSV rows are counted by pandas (so multi-line review text is handled).",
        "",
        "| CSV file | Table | CSV rows | DB rows | Match |",
        "|---|---|---:|---:|:---:|",
    ]
    for csv_name, table, csv_n, db_n in rows:
        lines.append(f"| {csv_name} | {table} | {csv_n:,} | {db_n:,} | {'yes' if csv_n == db_n else 'NO'} |")
    REPORT.parent.mkdir(exist_ok=True)
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
