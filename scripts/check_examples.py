"""Run every example in examples/examples.yaml and print the result, so Parth can check it by eye.

Local SQL only (read-only database, same guard as the app). No Gemini calls.
Parth sets `verified: true` in the YAML himself; this script never changes the YAML.

Run:  python scripts/check_examples.py            (prints + writes reports/examples_check.md)
      python scripts/check_examples.py ex04 ex12  (only these ids)
"""
import sqlite3
import sys
import time
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from ask_olist import db, guard  # noqa: E402

EXAMPLES = ROOT / "examples" / "examples.yaml"
REPORT = ROOT / "reports" / "examples_check.md"
ALL_TABLES = {
    "customers", "geolocation", "order_items", "order_payments", "order_reviews",
    "orders", "products", "sellers", "category_translation",
}
PREVIEW_ROWS = 8


def table(columns: list[str], rows: list[tuple]) -> str:
    lines = ["| " + " | ".join(columns) + " |", "|" + "|".join("---" for _ in columns) + "|"]
    lines += ["| " + " | ".join("NULL" if v is None else str(v) for v in r) + " |" for r in rows]
    return "\n".join(lines)


def main() -> int:
    examples = yaml.safe_load(EXAMPLES.read_text(encoding="utf-8"))
    wanted = set(sys.argv[1:])
    if wanted:
        examples = [e for e in examples if e["id"] in wanted]

    out, failures = [], 0
    for ex in examples:
        out += [f"## {ex['id']}: {ex['question']}", "", f"verified: {ex['verified']}   traps: {ex['traps']}   tables: {ex['tables']}", "",
                "```sql", ex["sql"].strip(), "```", ""]
        started = time.perf_counter()
        try:
            result = db.run_query(guard.check_sql(ex["sql"]))
        except (guard.GuardError, sqlite3.Error) as exc:
            failures += 1
            out += [f"**ERROR:** {type(exc).__name__}: {exc}", ""]
            continue
        seconds = time.perf_counter() - started
        shown = result.rows[:PREVIEW_ROWS]
        out += [f"{len(result.rows)} row(s), {seconds:.2f}s. First {len(shown)}:", "", table(result.columns, shown), ""]

    # Coverage summary (only meaningful when all examples are run)
    if not wanted:
        used_tables = {t for e in examples for t in e["tables"]}
        used_traps = {t for e in examples for t in e["traps"]}
        out += [
            "## Coverage", "",
            f"- examples: {len(examples)}, verified: {sum(bool(e['verified']) for e in examples)}, failed to run: {failures}",
            f"- tables not covered: {sorted(ALL_TABLES - used_tables) or 'none'}",
            f"- traps not covered: {sorted(set(range(1, 9)) - used_traps) or 'none'}", "",
        ]

    text = "\n".join(out)
    print(text)
    if not wanted:
        REPORT.write_text("# Example check (generated by scripts/check_examples.py)\n\n" + text, encoding="utf-8")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
