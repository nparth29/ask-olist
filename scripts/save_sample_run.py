"""Write reports/sample_run.md: one real RAG run of the app, for the README example.

The run itself was made with the real Gemini API (20 Nov 2026). This script replays it from the disk cache:
the API key is blanked below, so it makes ZERO API calls and fails loudly if the cache is missing.
Latency is not recorded, because a replay from the cache would show a misleading near-zero time.

Run:  python scripts/save_sample_run.py ["question"]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from ask_olist import config, pipeline  # noqa: E402

config.GEMINI_API_KEY = ""                     # zero API calls: a cache miss fails loudly
pipeline._log_attempt = lambda entry: None     # a replay is not a new run, so do not add it to logs/runs.jsonl

QUESTION = "Which 5 product categories had the most late deliveries in 2018?"
REPORT = ROOT / "reports" / "sample_run.md"


def add_line_breaks(sql: str) -> str:
    """Only inserts line breaks before main keywords, so the query text stays exactly what the model wrote."""
    flat = " ".join(sql.split())
    flat = re.sub(r" (FROM|LEFT JOIN|JOIN|WHERE|GROUP BY|ORDER BY|LIMIT) ", r"\n\1 ", flat)
    return re.sub(r" (AND) ", r"\n  \1 ", flat)


def main() -> None:
    question = sys.argv[1] if len(sys.argv) > 1 else QUESTION
    out = pipeline.ask(question, use_rag=True)
    pretty_sql = add_line_breaks(out["sql"])

    lines = [
        "# Sample run (RAG on)",
        "",
        "Generated by `scripts/save_sample_run.py`. The run was made with the real Gemini API; this file is a replay "
        "from the disk cache (no API calls). Only line breaks were added to the SQL for reading; the query text is what the model wrote.",
        "",
        f"**Question:** {question}",
        "",
        f"**Answer:** {out['answer']}",
        "",
        "**Assumptions the model stated:**",
        "",
        *[f"- {a}" for a in out["assumptions"]],
        "",
        "**SQL:**",
        "",
        "```sql",
        pretty_sql,
        "```",
        "",
        f"**Result** (first {len(out['rows'])} rows):",
        "",
        "| " + " | ".join(out["columns"]) + " |",
        "|" + "|".join("---" for _ in out["columns"]) + "|",
        *["| " + " | ".join(str(v) for v in row) + " |" for row in out["rows"]],
        "",
        "**Retrieved examples** (cosine similarity of the question to each verified example):",
        "",
        *[f"- {e['id']}  ({e['score']:.4f}): {e['question']}" for e in out["retrieved_examples"]],
        "",
        f"**Attempts needed:** {out['attempts']}",
        "",
    ]
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
