"""Write reports/thinking_level_test.md: default thinking vs thinking_level=low on the first sample questions.

Reads ONLY the disk cache (the results of the test run made on 20 Nov 2026). It cannot call the API:
the key is blanked below, so a cache miss raises an error instead of making a request.

Run:  python scripts/report_thinking_test.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from ask_olist import config, pipeline  # noqa: E402

config.GEMINI_API_KEY = ""                       # zero API calls: a cache miss fails loudly
pipeline._log_attempt = lambda entry: None       # do not add this replay to logs/runs.jsonl

REPORT = ROOT / "reports" / "thinking_level_test.md"

# The 5th sample question ("delivered orders per month in 2017") was never run with `low`:
# the free-tier daily limit ran out first. Only these four have both results in the cache.
QUESTIONS = [
    "Which 5 product categories had the most late deliveries in 2018?",
    "What was the total product revenue in 2017?",
    "How many customers placed more than one order?",
    "What is the total payment value for each payment type?",
]


def run(question: str, level: str | None) -> dict:
    config.LLM_THINKING_LEVEL = level
    return pipeline.ask(question, use_rag=False)   # zero-shot prompt (sql_v1), the one that was tested


def flat(rows: list[list]) -> str:
    return "; ".join(", ".join(str(v) for v in row) for row in rows)


def main() -> None:
    lines = [
        "# Thinking level test: default vs `low`",
        "",
        "Generated by `scripts/report_thinking_test.py` from the disk cache (no API calls). "
        "Model: `" + str(config.LLM_MODEL) + "`, zero-shot prompt `sql_v1`, 4 sample questions.",
        "",
        "Rule for keeping `low`: all sample answers must match. The 5th sample question was never run with `low` "
        "(the free-tier daily limit ran out), so only 4 are compared.",
        "",
        "| # | Question | Result, default thinking | Result, `low` | Same values? |",
        "|---|---|---|---|---|",
    ]
    same_count, details = 0, []
    for number, question in enumerate(QUESTIONS, 1):
        old, new = run(question, None), run(question, "low")
        same = old["rows"] == new["rows"]          # same values (column names may differ)
        same_count += same
        lines.append(f"| {number} | {question} | {flat(old['rows'])} | {flat(new['rows'])} | {'yes' if same else '**NO**'} |")
        if not same:
            details += [f"### Question {number}: {question}", "",
                        "Default thinking:", "```sql", old["sql"], "```", "Assumptions: " + "; ".join(old["assumptions"]), "",
                        "`low`:", "```sql", new["sql"], "```", "Assumptions: " + "; ".join(new["assumptions"]), ""]
    config.LLM_THINKING_LEVEL = None

    lines += ["", f"**{same_count} of {len(QUESTIONS)} questions gave the same values.**", ""]
    lines += details
    lines += [
        "## Speed",
        "",
        "No latency numbers are given here. The pipeline did not store latency per call, and the first-run timings "
        "included waiting on 503/504 overload retries, so they cannot be reproduced from a file.",
        "",
    ]
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
